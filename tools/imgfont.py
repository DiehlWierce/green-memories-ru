def trim(rows):
    if not rows: return rows,0
    cols=[x for x in range(len(rows[0])) if any(r[x]=='#' for r in rows)]
    if not cols: return rows,0
    x0,x1=min(cols),max(cols)
    return [r[x0:x1+1] for r in rows],x1-x0+1
def glyph(ch):
    rows,top=G[ch]
    r,w=trim(rows)
    return r,top,w
def adv(ch):
    if ch==' ': return 4
    r,top,w=glyph(ch)
    return w+1
def width(text): return sum(adv(c) for c in text)-1
def draw(a,x,y,text,color,bold=False):
    """a: numpy array; y=cap top row"""
    for ch in text:
        if ch==' ': x+=4; continue
        r,top,w=glyph(ch)
        for dy,row in enumerate(r):
            for dx,c in enumerate(row):
                if c=='#':
                    for ddx,ddy in ((0,0),(1,0),(0,1),(1,1)) if bold else ((0,0),):
                        yy=y+top+dy+ddy; xx=x+dx+ddx
                        if 0<=yy<a.shape[0] and 0<=xx<a.shape[1]: a[yy,xx]=color
        x+=w+(2 if bold else 1)
    return x
